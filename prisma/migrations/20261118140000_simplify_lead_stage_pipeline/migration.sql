-- Simplify the 12-stage pipeline down to a lean telecalling-style pipeline:
-- New Lead, DNP (Did Not Pick), Interested, Not Interested, Converted.
ALTER TABLE "Lead" ALTER COLUMN "status" DROP DEFAULT;
ALTER TABLE "Lead" ALTER COLUMN "status" TYPE TEXT USING ("status"::TEXT);
DROP TYPE "LeadStage";

CREATE TYPE "LeadStage" AS ENUM ('NEW_LEAD', 'DNP', 'INTERESTED', 'NOT_INTERESTED', 'CONVERTED');

UPDATE "Lead" SET "status" = CASE "status"
  WHEN 'NEW' THEN 'NEW_LEAD'
  WHEN 'ATTEMPTING_CONTACT' THEN 'DNP'
  WHEN 'CONTACTED' THEN 'INTERESTED'
  WHEN 'QUALIFIED' THEN 'INTERESTED'
  WHEN 'REQUIREMENT_CAPTURED' THEN 'INTERESTED'
  WHEN 'QUOTATION_IN_PROGRESS' THEN 'INTERESTED'
  WHEN 'QUOTATION_SENT' THEN 'INTERESTED'
  WHEN 'NEGOTIATION' THEN 'INTERESTED'
  WHEN 'WON' THEN 'CONVERTED'
  WHEN 'LOST' THEN 'NOT_INTERESTED'
  WHEN 'NURTURE' THEN 'INTERESTED'
  WHEN 'DISQUALIFIED' THEN 'NOT_INTERESTED'
  ELSE 'NEW_LEAD'
END;

ALTER TABLE "Lead" ALTER COLUMN "status" TYPE "LeadStage" USING ("status"::"LeadStage");
ALTER TABLE "Lead" ALTER COLUMN "status" SET DEFAULT 'NEW_LEAD';
ALTER TABLE "Lead" ALTER COLUMN "status" SET NOT NULL;
